#!/usr/bin/env python3
"""Read services.toml and derive everything that used to be repeated by hand.

Commands:
  generate [--check]            write (or verify) gitignored Caddy routes,
                                Compose bindings and environment files; also
                                writes the dashboard service list
  dns [primary|standby] [--change-batch]
                                DNS records the proxy needs, optionally as a
                                Route 53 change batch
  checks deploy|failover        tab-separated "name<TAB>path<TAB>optional" lines
"""

import json
import os
from pathlib import Path
import re
import sys
import tomllib


HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
NAME = re.compile(r"^[a-z0-9][a-z0-9-]*$")
CHECKS = ("deploy", "failover")
GROUPS = ("primary", "health")
SERVICE_KEYS = {"title", "icon", "dashboard", "path", "container", "placement",
                "tailnet", "checks", "optional", "proxy_path", "compose"}
HEADER = "# Generated by scripts/services.py from services.toml. Do not edit; run `make generate`.\n"
DASHBOARD_JSON = "services/caddy/www/src/services.json"


def default_file():
    if os.environ.get("SERVICES_FILE"):
        return Path(os.environ["SERVICES_FILE"])
    beside = HERE / "services.toml"
    return beside if beside.exists() else ROOT / "services.toml"


def load(path=None):
    with open(path or default_file(), "rb") as handle:
        config = tomllib.load(handle)
    validate(config)
    return config


def validate(config):
    hosts = config.get("hosts")
    if not isinstance(hosts, list) or not hosts or not all(
            isinstance(h, str) and NAME.match(h) for h in hosts) or len(set(hosts)) != len(hosts):
        raise ValueError("hosts must be a list of unique lowercase host names")
    for role in ("primary", "standby"):
        if config.get("proxy", {}).get(role) not in hosts:
            raise ValueError(f"proxy.{role} must be one of hosts")
    status = config.get("status", {})
    if (type(status.get("port")) is not int or not 1 <= status["port"] <= 65535
            or not isinstance(status.get("container"), str)
            or not re.fullmatch(r"[a-z0-9][a-z0-9-]*:[0-9]+", status["container"])):
        raise ValueError("status needs a port from 1 to 65535 and a lowercase container name:port")
    services = config.get("services")
    if not isinstance(services, dict) or not services:
        raise ValueError("services must not be empty")
    for name, service in services.items():
        if not NAME.match(name):
            raise ValueError(f"invalid service name {name}")
        unknown = set(service) - SERVICE_KEYS
        if unknown:
            raise ValueError(f"{name}: unknown keys {sorted(unknown)}")
        if ("container" in service) == ("tailnet" in service):
            raise ValueError(f"{name}: set exactly one of container or tailnet")
        if "tailnet" in service and (
                not isinstance(service["tailnet"], str) or not NAME.fullmatch(service["tailnet"])):
            raise ValueError(f"{name}: tailnet must be a lowercase machine name")
        if "proxy_path" in service and (
                not isinstance(service["proxy_path"], str)
                or not re.fullmatch(r"/[a-zA-Z0-9/_.-]*", service["proxy_path"])):
            raise ValueError(f"{name}: proxy_path must be an exact URL path using letters, "
                             "digits, slashes, underscores, dots or hyphens")
        if "container" in service:
            if (not isinstance(service["container"], str)
                    or not re.fullmatch(r"[a-z0-9][a-z0-9-]*:[0-9]+", service["container"])):
                raise ValueError(f"{name}: container must be a lowercase name:port")
            if "compose" in service and (
                    not isinstance(service["compose"], str) or not NAME.fullmatch(service["compose"])):
                raise ValueError(f"{name}: compose must name a directory under services")
            placement = service.get("placement")
            if not placement or not all(p.get("host") in hosts for p in placement):
                raise ValueError(f"{name}: placement must list known hosts")
            if any("port" in p and (type(p["port"]) is not int or not 1 <= p["port"] <= 65535)
                   for p in placement):
                raise ValueError(f"{name}: placement ports must be integers from 1 to 65535")
        elif "placement" in service or "compose" in service:
            raise ValueError(f"{name}: placement and compose only apply to containers")
        if "dashboard" in service and (service["dashboard"] not in GROUPS or not all(
                service.get(key) for key in ("title", "icon"))):
            raise ValueError(f"{name}: dashboard needs title, icon and a group of {GROUPS}")
        if not set(service.get("checks", [])) <= set(CHECKS):
            raise ValueError(f"{name}: checks must be from {CHECKS}")


def env_name(name):
    return name.upper().replace("-", "_")


def ip_var(host):
    return f"TAILSCALE_IP_{env_name(host)}"


def ip_ref(host):
    return "${%s:?Set %s}" % (ip_var(host), ip_var(host))


def host_ip(config, values, host):
    address = values.get(ip_var(host))
    if not address and host == config["proxy"]["primary"]:
        address = values.get("TAILSCALE_IP")
    return address


def host_ip_ref(config, host):
    if host == config["proxy"]["primary"]:
        return "${%s:-${TAILSCALE_IP:?Set TAILSCALE_IP or %s}}" % (ip_var(host), ip_var(host))
    return ip_ref(host)


def pihole_hosts(config):
    if not config["services"].get("pihole", {}).get("placement"):
        raise ValueError("services.pihole needs placements for DNS checks")
    return [entry["host"] for entry in config["services"]["pihole"]["placement"]]


def upstreams(config, caddy_host=None):
    """Caddy upstream variables as seen from caddy_host (None: everything local)."""
    values = {}
    for name, service in config["services"].items():
        if "container" not in service:
            continue
        placement = service["placement"]
        if caddy_host is None or any(p["host"] == caddy_host for p in placement):
            values[f"{env_name(name)}_UPSTREAM"] = service["container"]
            continue
        remote = next((p for p in placement if "port" in p), None)
        if remote is None:
            raise ValueError(f"{name} has no published port reachable from {caddy_host}")
        values[f"{env_name(name)}_UPSTREAM"] = f"{ip_ref(remote['host'])}:{remote['port']}"
    status = config["status"]
    for host in config["hosts"]:
        key = f"STATUS_{env_name(host)}_UPSTREAM"
        if caddy_host is None or host == caddy_host:
            values[key] = status["container"]
        else:
            values[key] = f"{ip_ref(host)}:{status['port']}"
    return values


def dashboard(config):
    services = []
    for name, service in config["services"].items():
        if "dashboard" in service:
            entry = {"service": name, "title": service["title"], "icon": service["icon"],
                     "group": service["dashboard"]}
            if "path" in service:
                entry["path"] = service["path"]
            services.append(entry)
    return {"hosts": config["hosts"], "services": services}


def applications(config):
    """Services probed by the live status agent: path by service name."""
    return {name: service.get("path", "/") for name, service in config["services"].items()
            if "dashboard" in service}


def checks(config, kind):
    """(name, path, optional) for each probe; the dashboard is named 'dashboard'."""
    rows = [("dashboard", "/", False)]
    for name, service in config["services"].items():
        if kind in service.get("checks", []):
            rows.append((name, service.get("path", "/"), bool(service.get("optional"))))
    return rows


def outputs(config):
    """Generated files by path relative to the repository root."""
    files = {}
    for label, host in [("single", None), (config["proxy"]["primary"], config["proxy"]["primary"]),
                        (config["proxy"]["standby"], config["proxy"]["standby"])]:
        lines = [f"{key}={value}" for key, value in upstreams(config, host).items()]
        files[f"services/caddy/generated/{label}.env"] = HEADER + "\n".join(lines) + "\n"
    files["services/caddy/generated/routes.caddy"] = caddy_routes(config)
    for host in config["hosts"]:
        files[f"services/caddy/generated/{host}.compose.yaml"] = compose_bindings(config, host)
    if "pihole" in config["services"]:
        files["services/caddy/generated/status.env"] = status_env(config)
        files["services/caddy/generated/pihole-sync.env"] = pihole_sync_env(config)
    return files


def compose_bindings(config, host):
    """Small extends definitions; application settings remain in base Compose files."""
    address = host_ip_ref(config, host)
    lines = [HEADER.rstrip(), "services:"]

    def binding(name, directory, ports, override=False):
        lines.extend([f"  {name}:", "    extends:",
                      f"      file: ../../{directory}/compose.yaml", f"      service: {name}",
                      "    ports:" + (" !override" if override else "")])
        lines.extend(f"      - {json.dumps(port)}" for port in ports)

    if host in config["proxy"].values():
        binding("caddy", "caddy", [f"{address}:80:80", f"{address}:443:443",
                                   f"{address}:443:443/udp"], override=True)
    status_name, status_port = config["status"]["container"].split(":")
    binding(status_name, "status", [f"{address}:{config['status']['port']}:{status_port}"],
            override=True)
    for name, service in config["services"].items():
        if "container" not in service:
            continue
        placement = next((entry for entry in service["placement"] if entry["host"] == host), None)
        if placement is None:
            continue
        container, port = service["container"].split(":")
        ports = [f"{address}:53:53/tcp", f"{address}:53:53/udp"] if name == "pihole" else []
        if "port" in placement:
            ports.append(f"{address}:{placement['port']}:{port}/tcp")
        if ports:
            binding(container, service.get("compose", container), ports, override=name == "pihole")
    return "\n".join(lines) + "\n"


def status_env(config):
    resolvers = {}
    for index, host in enumerate(pihole_hosts(config)):
        label = ("primary", "secondary")[index] if index < 2 else host
        resolvers[label] = (host_ip_ref(config, host) if index == 0
                            else "${%s:-}" % ip_var(host))
    return (HEADER + "DNS_RESOLVERS=" + json.dumps(resolvers) + "\n"
            + f"DNS_PRIMARY_PROXY={host_ip_ref(config, config['proxy']['primary'])}\n"
            + "DNS_STANDBY_PROXY=${%s:-}\n" % ip_var(config["proxy"]["standby"]))


def pihole_sync_env(config):
    service = config["services"]["pihole"]
    primary, *replicas = service["placement"]

    def password(host):
        key = f"PIHOLE_{env_name(host)}_PASSWORD"
        return "${%s:?Set %s}" % (key, key)

    addresses = []
    for replica in replicas:
        if "port" not in replica:
            raise ValueError(f"Pi-hole replica {replica['host']} needs a published port for sync")
        addresses.append(f"http://{ip_ref(replica['host'])}:{replica['port']}|"
                         f"{password(replica['host'])}")
    return (HEADER + f"PRIMARY=http://{service['container']}|{password(primary['host'])}\n"
            + "REPLICAS=" + ",".join(addresses) + "\n")


def caddy_routes(config):
    """Dashboard and service routes, shared by every proxy."""
    lines = [HEADER.rstrip(), "", "# Dashboard static server",
             "{$VPN_DOMAIN}, http:// {", "  import access_log",
             "  handle /status/applications {",
             f"    reverse_proxy {config['status']['container']}", "  }"]
    for host in config["hosts"]:
        lines.extend([f"  handle_path /status/{host} {{",
                      "    reverse_proxy {$STATUS_%s_UPSTREAM}" % env_name(host), "  }"])
    lines.extend(["  handle {", "    root * /usr/share/caddy",
                  "    rewrite /live-status /index.html", "    file_server", "  }", "}"])
    for name, service in config["services"].items():
        proxy = (f"import ts_upstream {service['tailnet']}" if "tailnet" in service
                 else "reverse_proxy {$%s_UPSTREAM}" % env_name(name))
        lines.extend(["", "%s.{$VPN_DOMAIN} {" % name, "  import access_log"])
        if "proxy_path" in service:
            lines.extend([f"  handle {service['proxy_path']} {{", f"    {proxy}", "  }",
                          "  handle {", '    respond "Not found" 404', "  }"])
        else:
            lines.append(f"  {proxy}")
        lines.append("}")
    return "\n".join(lines) + "\n"


def dashboard_json(config):
    """Dashboard service list; gitignored, so it is written at build time."""
    return json.dumps(dashboard(config), indent=2) + "\n"


def generate(config, check=False):
    stale = []
    for relative, text in outputs(config).items():
        path = ROOT / relative
        if path.exists() and path.read_text() == text:
            continue
        stale.append(relative)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    for relative in stale:
        print(("Out of date: " if check else "Wrote ") + relative)
    if check and stale:
        print("Run `make generate`.", file=sys.stderr)
    if not check:
        (ROOT / DASHBOARD_JSON).write_text(dashboard_json(config))
        print(f"Wrote {DASHBOARD_JSON}")
    return 1 if check and stale else 0


def parse_env(text):
    values = {}
    for line in text.splitlines():
        key, separator, value = line.partition("=")
        if separator and key.strip() and not key.strip().startswith("#"):
            values[key.strip()] = value.strip().strip("\"'")
    return values


def read_env(path=None, environment=None):
    env_file = Path(path) if path is not None else ROOT / ".env"
    values = parse_env(env_file.read_text()) if env_file.exists() else {}
    environment = os.environ if environment is None else environment
    values.update({key: value for key, value in environment.items() if key == "VPN_DOMAIN"
                   or key.startswith("TAILSCALE_IP")})
    return values


def dns_records(config, which, env):
    host = config["proxy"][which]
    domain, address = env.get("VPN_DOMAIN"), env.get(ip_var(host))
    if not domain or not address:
        raise ValueError(f"Set VPN_DOMAIN and {ip_var(host)} in .env")
    return host, [(domain, address), (f"*.{domain}", address)]


def change_batch(host, records):
    return {"Comment": f"centcom proxy -> {host}", "Changes": [
        {"Action": "UPSERT", "ResourceRecordSet": {
            "Name": name + ".", "Type": "A", "TTL": 300, "ResourceRecords": [{"Value": address}]}}
        for name, address in records]}


def main(argv):
    command = argv[1] if len(argv) > 1 else ""
    flags = [a for a in argv[2:] if a.startswith("--")]
    args = [a for a in argv[2:] if not a.startswith("--")]
    try:
        config = load()
        if command == "generate":
            return generate(config, check="--check" in flags)
        if command == "checks" and args and args[0] in CHECKS:
            for name, path, optional in checks(config, args[0]):
                print(f"{name}\t{path}\t{'optional' if optional else ''}")
            return 0
        if command == "dns":
            which = args[0] if args else "primary"
            if which not in ("primary", "standby"):
                raise ValueError("choose primary or standby")
            env = read_env()
            host, records = dns_records(config, which, env)
            if "--change-batch" in flags:
                print(json.dumps(change_batch(host, records), indent=2))
                return 0
            print(f"Proxy {which} ({host}): point these A records at its Tailscale IP")
            for name, address in records:
                print(f"  {name}\tA\t{address}")
            domain = env["VPN_DOMAIN"]
            print("Hostnames served (covered by the wildcard unless an exact record exists;"
                  " exact records override it and must be changed too):")
            for label in ["", *config["services"]]:
                print(f"  {label + '.' if label else ''}{domain}")
            return 0
    except (OSError, ValueError, tomllib.TOMLDecodeError) as error:
        print(f"services.toml: {error}", file=sys.stderr)
        return 1
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
